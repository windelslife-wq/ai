/**
 * Generated SEO documents: `robots.txt`, `sitemap.xml`, `manifest.webmanifest`.
 *
 * Legacy parity: `application/controllers/Seo.php` builds robots and sitemap from
 * `application/config/seo.php`, which reads `VP_*` environment variables. These
 * builders read the validated `config.site` produced by `src/config.js`
 * (`SITE_*` / `PUBLIC_BASE_URL`), so a deployment configures one SEO surface and
 * every document agrees with it.
 *
 * Both documents are generated per request rather than committed as static files:
 * a static `sitemap.xml` in a repository silently advertises the wrong origin on
 * every host it is deployed to.
 */

import { DISALLOWED_PREFIXES, sitemapPaths } from "./pages.js";

/** Icon set generated by `tools/generate-icons.mjs`; sizes are asserted there. */
export const ICONS = Object.freeze([
  { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
  { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
  { src: "/icons/maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  { src: "/icons/windels-mark.svg", sizes: "any", type: "image/svg+xml", purpose: "any" },
]);

export function robotsTxt(seo, { paths = DISALLOWED_PREFIXES } = {}) {
  const lines = ["User-agent: *", "Allow: /"];
  for (const prefix of paths) lines.push(`Disallow: ${prefix}`);
  // A Sitemap line with no origin is worse than none: crawlers resolve it
  // against the request host, which on a staging subdomain points at staging.
  if (seo.canonicalBase) lines.push(`Sitemap: ${seo.canonicalBase}/sitemap.xml`);
  return `${lines.join("\n")}\n`;
}

function escapeXml(value) {
  return String(value ?? "").replace(/[<>&'"]/g, (character) => (
    { "<": "&lt;", ">": "&gt;", "&": "&amp;", "'": "&apos;", '"': "&quot;" }[character]
  ));
}

/**
 * Absolute URLs when a canonical origin is configured, relative ones when it is
 * not (development). A relative `<loc>` is invalid per sitemaps.org, so in that
 * case the document says so in a comment instead of publishing broken entries.
 */
export function sitemapXml(seo, { paths = sitemapPaths() } = {}) {
  const header = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">';
  if (!seo.canonicalBase) {
    return `${header}\n<!-- PUBLIC_BASE_URL is not configured, so no absolute URL can be published. Set it and this sitemap lists ${paths.length} pages. -->\n</urlset>\n`;
  }
  const entries = paths.map((path) => `  <url>\n    <loc>${escapeXml(`${seo.canonicalBase}${path}`)}</loc>\n  </url>`);
  return `${header}\n${entries.join("\n")}\n</urlset>\n`;
}

export function webManifest(seo) {
  return {
    id: "/app/",
    name: seo.name,
    short_name: seo.name.split(" ").slice(0, 2).join(" ").slice(0, 32),
    description: seo.description,
    // The installable surface is the workspace, not the marketing pages.
    start_url: "/app/",
    scope: "/",
    display: "standalone",
    orientation: "any",
    background_color: seo.backgroundColor,
    theme_color: seo.themeColor,
    categories: ["business", "productivity", "education"],
    lang: "en",
    dir: "ltr",
    icons: ICONS.map((icon) => ({ ...icon })),
  };
}

/**
 * The service worker, generated per deployment (finding F-09).
 *
 * Why it is not a committed file: a precache list that names hashed asset files is
 * stale the moment the next build lands, and a hand-maintained `CACHE_NAME` is
 * forgotten exactly when the shell changes. Here the cache name *is* a content hash
 * of the shell (styles, script, manifest, icons), so any edit to them changes the
 * version, a new worker installs, and the page can offer an update — no discipline
 * required, nothing to forget.
 *
 * Caching policy, in one place:
 *   shell documents (/, /app/)   network-first, cached copy is the offline fallback
 *   hashed assets (/app/assets/) cache-first — the name contains the content hash,
 *                                so a cached copy is by definition current
 *   everything else same-origin  stale-while-revalidate
 *   /api/, uploads, private paths, mutations  never cached
 */
/**
 * Paths the worker must never cache. Exported so the test suite asserts the policy
 * as data instead of pattern-matching generated source text.
 */
export const SERVICE_WORKER_NEVER_CACHE = Object.freeze(["/api/", "/uploads/", "/private/", "/data/", "/service-worker.js", "/contact/submit"]);

/**
 * Renders one entry of the never-cache list as a RegExp literal for the worker.
 * Exported so the test suite can compute the exact expected source text instead of
 * trusting that generation kept the policy.
 */
export function neverCachePatternLiteral(prefix) {
  const escaped = prefix.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
  return `/^${escaped}/`;
}

export function serviceWorkerSource({ version, precache, neverCache = SERVICE_WORKER_NEVER_CACHE }) {
  const shell = JSON.stringify(precache, null, 2).replace(/\n/g, "\n  ");
  const neverLine = `const NEVER_CACHE = [${neverCache.map(neverCachePatternLiteral).join(", ")}];`;
  const source = SOURCE_TEMPLATE
    .replace("__CACHE_NAME__", `windels-shell-${version}`)
    .replace("__SHELL__", shell)
    .replace("__NEVER_LINE__", neverLine);
  return source;
}

const SOURCE_TEMPLATE = `/* WINDELS AI WORKFORCE service worker — generated; do not edit. */
const CACHE = "__CACHE_NAME__";
const SHELL = __SHELL__;
const HASHED_ASSET = /\\/assets\\/[A-Za-z0-9_.-]+-[A-Za-z0-9_-]{8,}\\.(?:js|css|png|jpg|jpeg|svg|webp|woff2)$/;
__NEVER_LINE__

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // One missing shell file must fail the install: a half-cached shell is the
    // offline state that shows a blank page instead of the site.
    await cache.addAll(SHELL);
    // First visit: no controller, nothing to wait for — activate now. An update on
    // an open page stays waiting instead, so the page can offer the reload itself.
    if (!self.clients?.matchAll) return self.skipWaiting();
    const clients = await self.clients.matchAll({ type: "window" });
    const controlled = clients.some((client) => client.url !== self.location.href);
    if (!controlled) await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith("windels-") && key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
    const clients = await self.clients.matchAll({ type: "window" });
    for (const client of clients) client.postMessage({ type: "windels:activated", version: CACHE });
  })());
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (NEVER_CACHE.some((pattern) => pattern.test(url.pathname))) return;

  if (request.mode === "navigate") {
    const shellPath = url.pathname === "/app" || url.pathname.startsWith("/app/") ? "/app/" : "/";
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok && (response.headers.get("content-type") || "").includes("text/html")) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(shellPath, copy));
        }
        return response;
      } catch (error) {
        return (await caches.match(shellPath)) || (await caches.match("/")) || Response.error();
      }
    })());
    return;
  }

  if (HASHED_ASSET.test(url.pathname)) {
    // Content-hashed name: a cache hit is current by construction, and a miss is
    // stored forever-safe because the next build will use a new name.
    event.respondWith((async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok && response.type === "basic") {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request);
    const refresh = fetch(request).then((response) => {
      if (response.ok && response.type === "basic") {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    }).catch(() => null);
    return cached || (await refresh) || Response.error();
  })());
});
`;
